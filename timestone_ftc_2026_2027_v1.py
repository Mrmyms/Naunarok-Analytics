def simulate_alliance(EVENT, r1, r2, color, scouting_df, teams_names_df, matches_df):
    robots = {
        "robot1": simulate_robot(EVENT, r1, scouting_df, teams_names_df, matches_df),
        "robot2": simulate_robot(EVENT, r2, scouting_df, teams_names_df, matches_df)
    }

    r1s, r2s = robots["robot1"], robots["robot2"]

    auto_std = round(np.sqrt(r1s.get("auto_var", 0) + r2s.get("auto_var", 0)))
    tele_std = round(np.sqrt(r1s.get("tele_var", 0) + r2s.get("tele_var", 0)))

    auto_est     = r1s["auto_avg"] + r2s["auto_avg"]
    tele_est_raw = r1s["tele_avg"] + r2s["tele_avg"]

    # Sinergia colaborativa en Flores
    alliance_can_top_nectar = (
        r1s.get("can_top_nectar") == "SI" or r2s.get("can_top_nectar") == "SI"
    )
    total_flower_pieces = r1s.get("est_flower_pieces", 0.0) + r2s.get("est_flower_pieces", 0.0)
    max_pieces_2_flores = 2 * CAPACIDAD_FLOR

    if alliance_can_top_nectar:
        alliance_flores_tapadas = round(min(2.0, total_flower_pieces / CAPACIDAD_FLOR), 2)
        piezas_excedentes = max(0.0, total_flower_pieces - max_pieces_2_flores)
        ajuste_flor_pts = -round(piezas_excedentes * SCORES["FLOWER CELL"])
    else:
        alliance_flores_tapadas = 0.0
        pts_flor_brutos = total_flower_pieces * SCORES["FLOWER CELL"]
        ajuste_flor_pts = -round(pts_flor_brutos * 0.5)

    tele_est = max(0, tele_est_raw + ajuste_flor_pts)

    end_est  = r1s["endgame_est"] + r2s["endgame_est"]
    end_min  = r1s["endgame_min"] + r2s["endgame_min"]
    end_max  = r1s["endgame_max"] + r2s["endgame_max"]

    total_tips_est  = r1s["est_tips"] + r2s["est_tips"]
    total_swarm_est = r1s["swarm_pts_est"] + r2s["swarm_pts_est"]

    score = {
        "EVENT"                  : EVENT,
        "color"                  : "BLUE" if color == 0 else "RED",
        "auto_std"               : auto_std,
        "tele_std"               : tele_std,
        "auto_est"               : auto_est,
        "auto_min"               : max(0, auto_est - auto_std),
        "auto_max"               : auto_est + auto_std,
        "tele_est"               : tele_est,
        "tele_min"               : max(0, tele_est - tele_std),
        "tele_max"               : tele_est + tele_std,
        "end_est"                : end_est,
        "est_tips"               : round(total_tips_est, 1),
        "swarm_pts_est"          : round(total_swarm_est, 1),

        "alliance_top_nectar"    : "SI" if alliance_can_top_nectar else "NO",
        "alliance_flower_pieces" : round(total_flower_pieces, 1),
        "alliance_flores_tapadas": alliance_flores_tapadas,

        "auto_leave_1"           : r1s["auto_leave"],
        "auto_leave_2"           : r2s["auto_leave"],
        "auto_park_1"            : r1s["auto_park"],
        "auto_park_2"            : r2s["auto_park"],
        "tele_park_1"            : r1s["tele_park"],
        "tele_park_2"            : r2s["tele_park"],

        "score_est_total"        : auto_est + tele_est + end_est,
        "score_min_total"        : max(0, auto_est - auto_std) + max(0, tele_est - tele_std) + end_min,
        "score_max_total"        : (auto_est + auto_std) + (tele_est + tele_std) + end_max,
    }

    score["SWARM RP"]        = RP["SWARM RP"]       if total_swarm_est >= RP_THRESHOLDS["SWARM_POINTS"] else 0
    score["POLLINATOR 1 RP"] = RP["POLINATOR 1 RP"] if total_tips_est  >= RP_THRESHOLDS["POLLINATOR_1"] else 0
    score["POLLINATOR 2 RP"] = RP["POLINATOR 2 RP"] if total_tips_est  >= RP_THRESHOLDS["POLLINATOR_2"] else 0

    return score, robots


def simulate_match(EVENT, match_num, scouting_df, teams_names_df, matches_df):
    if matches_df.empty:
        print(f"[WARN] [{EVENT}] simulate_match: matches_df está vacío.")
        return {}, {}

    m_id = normalise_match_id(match_num)
    row_df = matches_df.loc[matches_df["match_code"] == m_id]
    if row_df.empty:
        print(f"[WARN] [{EVENT}] simulate_match: match {match_num} no encontrado.")
        return {}, {}

    row   = row_df.iloc[0]
    red1  = int(row.get("RED1",  0))
    red2  = int(row.get("RED2",  0))
    blue1 = int(row.get("BLUE1", 0))
    blue2 = int(row.get("BLUE2", 0))

    red_score,  red_robots  = simulate_alliance(EVENT, red1, red2, 1, scouting_df, teams_names_df, matches_df)
    blue_score, blue_robots = simulate_alliance(EVENT, blue1, blue2, 0, scouting_df, teams_names_df, matches_df)

    robots = {
        "red1" : red_robots["robot1"],  "red2" : red_robots["robot2"],
        "blue1": blue_robots["robot1"], "blue2": blue_robots["robot2"],
    }

    alliances = {"RED": red_score, "BLUE": blue_score}
    return alliances, robots

######## CELL 6 — Construcción de tablas maestras ########

def build_export_tables(EVENT, scouting_df, teams_names_df, matches_df):
    """Construye los DataFrames completos de Ranking EPA, Robots, Alianzas y Standings."""
    # 1. Tabla completa de robots individuales + Ranking ejecutivo
    robots_full = []
    ranking_rows = []

    for _, t_row in teams_names_df.iterrows():
        tid = int(t_row["Team ID"])
        r_dict = simulate_robot(EVENT, tid, scouting_df, teams_names_df, matches_df)

        r_clean = r_dict.copy()
        r_clean["auto_scores"] = str(r_clean["auto_scores"])
        r_clean["tele_scores"] = str(r_clean["tele_scores"])
        robots_full.append(r_clean)

        ranking_rows.append({
            "EVENTO"         : EVENT,
            "Team ID"        : r_dict["team_id"],
            "Nombre"         : r_dict["name"],
            "Matches"        : r_dict["matches_played"],
            "EPA"            : r_dict["EPA"],
            "Score Est"      : r_dict["score_est"],
            "Auto Est"       : r_dict["auto_est"],
            "Tele Est"       : r_dict["tele_est"],
            "End Est"        : r_dict["endgame_est"],
            "Tips Est"       : r_dict["est_tips"],
            "Top Nectar"     : r_dict["can_top_nectar"],
            "Flores TOP" : r_dict["flores_llenadas_est"],
            "Piezas Flor"    : r_dict["est_flower_pieces"],
            "Pos Estimada"   : r_dict["pos_type"],
        })

    df_robots = pd.DataFrame(robots_full)
    if not df_robots.empty:
        df_robots = df_robots.sort_values(by="EPA", ascending=False).reset_index(drop=True)

    ranking_df = pd.DataFrame(ranking_rows)
    if not ranking_df.empty:
        ranking_df = ranking_df.sort_values(by="EPA", ascending=False).reset_index(drop=True)
        ranking_df.insert(0, "Rank_EPA", ranking_df.index + 1)

    # 2. Simulación por Match (Alianzas Roja/Azul + Resumen + Proyección de Standings)
    red_rows   = []
    blue_rows  = []
    match_summary_rows = []

    rp_tracker = {
        int(t): {"Team ID": int(t), "Nombre": n, "PJ_Sim": 0, "RPs_Totales": 0, "Score_Acumulado": 0}
        for t, n in zip(teams_names_df["Team ID"], teams_names_df["Names"])
    }

    for _, m_row in matches_df.iterrows():
        m_code = m_row["match_code"]
        alliances, _ = simulate_match(EVENT, m_code, scouting_df, teams_names_df, matches_df)
        if not alliances:
            continue

        red, blue = alliances["RED"], alliances["BLUE"]

        if red["score_est_total"] > blue["score_est_total"]:
            red_win_rp, blue_win_rp, ganador = 3, 0, "RED"
        elif blue["score_est_total"] > red["score_est_total"]:
            red_win_rp, blue_win_rp, ganador = 0, 3, "BLUE"
        else:
            red_win_rp, blue_win_rp, ganador = 1, 1, "EMPATE"

        red_total_rp  = red_win_rp  + red["SWARM RP"]  + red["POLLINATOR 1 RP"]  + red["POLLINATOR 2 RP"]
        blue_total_rp = blue_win_rp + blue["SWARM RP"] + blue["POLLINATOR 1 RP"] + blue["POLLINATOR 2 RP"]

        red_rows.append({"Match": m_code, "RED1": m_row["RED1"], "RED2": m_row["RED2"], **red, "Resultado": ganador, "Total_RPs": red_total_rp})
        blue_rows.append({"Match": m_code, "BLUE1": m_row["BLUE1"], "BLUE2": m_row["BLUE2"], **blue, "Resultado": ganador, "Total_RPs": blue_total_rp})

        match_summary_rows.append({
            "EVENTO"           : EVENT,
            "Match"            : m_code,
            "RED1"             : m_row["RED1"],
            "RED2"             : m_row["RED2"],
            "BLUE1"            : m_row["BLUE1"],
            "BLUE2"            : m_row["BLUE2"],
            "Red Est"          : red["score_est_total"],
            "Blue Est"         : blue["score_est_total"],
            "Ganador Est"      : ganador,
            "Red Flores Tap."  : red["alliance_flores_tapadas"],
            "Blue Flores Tap." : blue["alliance_flores_tapadas"],
            "Red RPs Est"      : red_total_rp,
            "Blue RPs Est"     : blue_total_rp,
        })

        for team_key, pts, rps in [
            (m_row["RED1"], red["score_est_total"], red_total_rp),
            (m_row["RED2"], red["score_est_total"], red_total_rp),
            (m_row["BLUE1"], blue["score_est_total"], blue_total_rp),
            (m_row["BLUE2"], blue["score_est_total"], blue_total_rp),
        ]:
            t_int = int(team_key)
            if t_int in rp_tracker:
                rp_tracker[t_int]["PJ_Sim"]          += 1
                rp_tracker[t_int]["RPs_Totales"]     += rps
                rp_tracker[t_int]["Score_Acumulado"] += pts

    df_red_alliance  = pd.DataFrame(red_rows)
    df_blue_alliance = pd.DataFrame(blue_rows)
    sim_matches_df   = pd.DataFrame(match_summary_rows)

    df_standings = pd.DataFrame(list(rp_tracker.values()))
    if not df_standings.empty:
        df_standings["RP_Promedio"] = (df_standings["RPs_Totales"] / df_standings["PJ_Sim"].replace(0, 1)).round(2)
        df_standings = df_standings.sort_values(
            by=["RP_Promedio", "Score_Acumulado"], ascending=[False, False]
        ).reset_index(drop=True)
        df_standings.insert(0, "Rank_Proyectado", df_standings.index + 1)

    return ranking_df, df_robots, sim_matches_df, df_red_alliance, df_blue_alliance, df_standings

######## CELL 7 — Exportar resultados a google sheets ########
def upload_dataframes(gss_obj, dataframes_dict):
    """Sube múltiples DataFrames a pestañas de Google Sheets creando o limpiando cada hoja."""
    for sheet_name, df in dataframes_dict.items():
        if df is None or df.empty:
            print(f"[SKIP] '{sheet_name}' está vacío, no se subió.")
            continue
        try:
            ws = gss_obj.worksheet(sheet_name)
            ws.clear()
        except gspread.exceptions.WorksheetNotFound:
            ws = gss_obj.add_worksheet(
                title=sheet_name,
                rows=str(len(df) + 15),
                cols=str(len(df.columns) + 5)
            )
        set_with_dataframe(ws, df)
        print(f"  -> Pestaña '{sheet_name}' actualizada ({len(df)} filas).")
    print("[OK] Todas las tablas fueron exportadas exitosamente a Google Sheets.")


