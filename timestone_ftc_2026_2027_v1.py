def simulate_robot(EVENT, team_id, scouting_df, teams_names_df, matches_df):
    robot = {
        "EVENT"                    : EVENT,
        "team_id"                  : int(team_id),
        "name"                     : "UNKNOWN",
        "matches_played"           : 0,

        "pos_a"                    : 0,
        "pos_b"                    : 0,
        "pos_c"                    : 0,
        "pos_d"                    : 0,
        "pos_e"                    : 0,
        "pos_type"                 : "NONE",

        "auto_leave"               : "NO",
        "auto_park"                : "NO",
        "tele_park"                : "NO",
        "can_top_nectar"           : "NO",

        "game_piece_pollen"        : "NO",
        "game_piece_nectar"        : "NO",
        "game_piece_flower_pollen" : "NO",
        "game_piece_flower_nectar" : "NO",
        "game_piece_hive_pollen"   : "NO",
        "game_piece_hive_nectar"   : "NO",

        "est_tips"                 : 0.0,
        "swarm_pts_est"            : 0.0,
        "flores_llenadas_est"      : 0.0,
        "est_flower_pieces"        : 0.0,

        "auto_scores"              : [],
        "tele_scores"              : [],

        "auto_avg"                 : 0,
        "auto_std"                 : 0,
        "auto_var"                 : 0,
        "tele_avg"                 : 0,
        "tele_std"                 : 0,
        "tele_var"                 : 0,
        "endgame_est"              : 0,
        "endgame_min"              : 0,
        "endgame_max"              : 0,

        "auto_est"                 : 0,
        "auto_min"                 : 0,
        "auto_max"                 : 0,
        "tele_est"                 : 0,
        "tele_min"                 : 0,
        "tele_max"                 : 0,
        "score_est"                : 0,
        "score_min"                : 0,
        "score_max"                : 0,
        "EPA"                      : 0,
    }

    try:
        name_row = teams_names_df.loc[teams_names_df["Team ID"] == team_id, "Names"]
        robot["name"] = name_row.values[0] if not name_row.empty else "UNKNOWN"

        if scouting_df.empty or "EQUIPO" not in scouting_df.columns:
            return robot

        data = scouting_df.loc[scouting_df["EQUIPO"] == team_id].reset_index(drop=True).fillna(0)
        if data.empty:
            return robot

        robot["matches_played"] = len(data)

        # ── ESTADOS Y POSICIÓN INICIAL ─────────────────────────────────────────
        if "AUTO LEAVE" in data.columns:
            robot["auto_leave"] = safe_mode(temporal_weight(data["AUTO LEAVE"]), "NO")
        if "AUTO PARK" in data.columns:
            robot["auto_park"] = safe_mode(temporal_weight(data["AUTO PARK"]), "NO")
        if "ENDGAME PARK" in data.columns:
            robot["tele_park"] = safe_mode(temporal_weight(data["ENDGAME PARK"]), "NO")

        if "POS INICIAL" in data.columns:
            weighted_eg = [str(p).strip() for p in temporal_weight(data["POS INICIAL"])]
            if weighted_eg:
                n = len(weighted_eg)
                robot["pos_a"]     = round(sum("A" in p for p in weighted_eg) / n * 100)
                robot["pos_b"]     = round(sum("B" in p for p in weighted_eg) / n * 100)
                robot["pos_c"]     = round(sum("C" in p for p in weighted_eg) / n * 100)
                robot["pos_d"]     = round(sum("D" in p for p in weighted_eg) / n * 100)
                robot["pos_e"]     = round(sum("E" in p.upper() for p in weighted_eg) / n * 100)
                robot["pos_type"]  = safe_mode(weighted_eg, "NONE")

        # ── CÁLCULO MATCH POR MATCH ────────────────────────────────────────────
        match_auto_pts       = []
        match_tele_pts       = []
        match_end_pts        = []
        match_tips           = []
        match_swarm          = []
        match_flores_tapadas = []
        match_flower_pieces  = []

        for _, row in data.iterrows():
            leave_pts = SCORES["AUTO LEAVE"] if str(row.get("AUTO LEAVE", "")).upper() in ["SI", "SÍ", "YES", "1", "TRUE"] else 0
            apark_pts = SCORES["AUTO PARK"]  if str(row.get("AUTO PARK", "")).upper()  in ["SI", "SÍ", "YES", "1", "TRUE"] else 0
            epark_pts = SCORES["TELE PARK"]  if str(row.get("ENDGAME PARK", "")).upper() in ["SI", "SÍ", "YES", "1", "TRUE"] else 0

            match_swarm.append(leave_pts + apark_pts + epark_pts)

            # AUTO
            a_hive_p = float(row.get("AUTO HIVE POLEN", 0))
            a_hive_n = float(row.get("AUTO HIVE NÉCTAR", 0))
            a_flor_p = float(row.get("AUTO FLOR POLEN", 0))
            a_flor_n = float(row.get("AUTO FLOR NÉCTAR", 0))

            a_weight = (a_hive_p * PESO["POLLEN"]) + (a_hive_n * PESO["NECTAR"])
            a_tips   = int(a_weight // PESO["TIP"])

            a_pts = (
                leave_pts + apark_pts +
                (a_tips * SCORES["HIVE TIP"]) +
                ((a_hive_p + a_hive_n) * SCORES["HIVE CELL"])
            )
            match_auto_pts.append(a_pts)

            # TELEOP
            t_hive_p  = float(pd.to_numeric(row.get("TELE HIVE POLEN", 0), errors="coerce") or 0)
            t_hive_n  = float(pd.to_numeric(row.get("TELE HIVE NÉCTAR", 0), errors="coerce") or 0)
            t_flor_p  = float(pd.to_numeric(row.get("TELE FLOR POLEN", 0), errors="coerce") or 0)
            t_flor_n  = float(pd.to_numeric(row.get("TELE FLOR NÉCTAR", 0), errors="coerce") or 0)
            garden_p  = float(pd.to_numeric(row.get("GARDEN PIEZAS", 0), errors="coerce") or 0)

            bot_raw   = str(row.get("BOTTOM NÉCTAR", "NO")).strip().upper()
            bot_nect  = SCORES["BOTTOM NECTAR"] if bot_raw in ["SI", "SÍ", "YES", "1", "TRUE"] else 0

            prop_str  = str(row.get("PROPIEDAD FLOR", "")).strip().upper()
            prop_flor = prop_str in ["SI", "SÍ", "YES", "1", "TRUE", "1 FLOR", "2 FLORES"]

            t_weight = (t_hive_p * PESO["POLLEN"]) + (t_hive_n * PESO["NECTAR"])
            t_tips   = int(t_weight // PESO["TIP"])
            match_tips.append(a_tips + t_tips)

            flower_total_pieces = a_flor_p + a_flor_n + t_flor_p + t_flor_n
            match_flower_pieces.append(flower_total_pieces)
            flower_pts = flower_total_pieces * SCORES["FLOWER CELL"]

            puede_top_nectar = (a_flor_n + t_flor_n) >= 1 or prop_flor
            flores_tapadas_match = min(2.0, flower_total_pieces / CAPACIDAD_FLOR) if puede_top_nectar else 0.0
            match_flores_tapadas.append(flores_tapadas_match)

            t_pts = (
                (t_tips * SCORES["HIVE TIP"]) +
                ((t_hive_p + t_hive_n) * SCORES["HIVE CELL"]) +
                flower_pts +
                bot_nect +
                (garden_p * SCORES["GARDEN CELL"])
            )
            match_tele_pts.append(t_pts)
            match_end_pts.append(epark_pts)

        # ── BANDERAS DE CAPACIDAD DE PIEZAS ────────────────────────────────────
        if (data.get("AUTO FLOR POLEN", 0).sum() + data.get("TELE FLOR POLEN", 0).sum()) >= 1:
            robot["game_piece_pollen"] = "SI"
            robot["game_piece_flower_pollen"] = "SI"
        if (data.get("AUTO FLOR NÉCTAR", 0).sum() + data.get("TELE FLOR NÉCTAR", 0).sum()) >= 1:
            robot["game_piece_nectar"] = "SI"
            robot["game_piece_flower_nectar"] = "SI"
            robot["can_top_nectar"] = "SI"
        if (data.get("AUTO HIVE POLEN", 0).sum() + data.get("TELE HIVE POLEN", 0).sum()) >= 1:
            robot["game_piece_pollen"] = "SI"
            robot["game_piece_hive_pollen"] = "SI"
        if (data.get("AUTO HIVE NÉCTAR", 0).sum() + data.get("TELE HIVE NÉCTAR", 0).sum()) >= 1:
            robot["game_piece_nectar"] = "SI"
            robot["game_piece_hive_nectar"] = "SI"

        if "PROPIEDAD FLOR" in data.columns:
            if data["PROPIEDAD FLOR"].astype(str).str.upper().isin(["SI", "SÍ", "YES", "1", "TRUE", "1 FLOR", "2 FLORES"]).any():
                robot["can_top_nectar"] = "SI"

        # ── ESTADÍSTICAS CON PONDERACIÓN TEMPORAL ──────────────────────────────
        robot["auto_scores"] = match_auto_pts
        robot["tele_scores"] = match_tele_pts

        w_auto = temporal_weight(match_auto_pts)
        w_tele = temporal_weight(match_tele_pts)
        w_end  = temporal_weight(match_end_pts)

        robot["auto_avg"] = round(np.mean(w_auto))
        robot["auto_std"] = round(np.std(w_auto))
        robot["auto_var"] = round(np.var(w_auto))

        robot["tele_avg"] = round(np.mean(w_tele))
        robot["tele_std"] = round(np.std(w_tele))
        robot["tele_var"] = round(np.var(w_tele))

        robot["endgame_est"] = round(np.mean(w_end))
        robot["endgame_min"] = max(0, round(robot["endgame_est"] - np.std(w_end)))
        robot["endgame_max"] = round(robot["endgame_est"] + np.std(w_end))

        robot["est_tips"]            = round(np.mean(temporal_weight(match_tips)), 1)
        robot["swarm_pts_est"]       = round(np.mean(temporal_weight(match_swarm)), 1)
        robot["flores_llenadas_est"] = round(np.mean(temporal_weight(match_flores_tapadas)), 2)
        robot["est_flower_pieces"]   = round(np.mean(temporal_weight(match_flower_pieces)), 1)

        robot["auto_est"]  = robot["auto_avg"]
        robot["auto_min"]  = max(0, robot["auto_est"] - robot["auto_std"])
        robot["auto_max"]  = robot["auto_est"] + robot["auto_std"]

        robot["tele_est"]  = robot["tele_avg"]
        robot["tele_min"]  = max(0, robot["tele_est"] - robot["tele_std"])
        robot["tele_max"]  = robot["tele_est"] + robot["tele_std"]

        robot["score_est"] = robot["auto_est"] + robot["tele_est"] + robot["endgame_est"]
        robot["score_min"] = robot["auto_min"] + robot["tele_min"] + robot["endgame_min"]
        robot["score_max"] = robot["auto_max"] + robot["tele_max"] + robot["endgame_max"]

        robot["EPA"] = round(0.35 * robot["auto_est"] + 0.55 * robot["tele_est"] + 0.10 * robot["endgame_est"], 1)

    except Exception as e:
        print(f"[ERROR] simulate_robot [{EVENT}] team {team_id}: {e}")

    return robot

