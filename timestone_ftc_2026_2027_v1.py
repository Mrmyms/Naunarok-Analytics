def load_event_data(spreadsheet, event_code):
    """
    Carga y filtra scouting_df, teams_names_df y matches_df específicamente
    para el evento indicado en `event_code`.
    Soporta tanto pestañas por evento ('Scouting_MXTO') como la hoja principal ('Captura_BIOBUZZ').
    """
    sheet_titles = [ws.title for ws in spreadsheet.worksheets()]

    # ── 1. CARGA DE SCOUTING ───────────────────────────────────────────────────
    if f"Scouting_{event_code}" in sheet_titles:
        scouting_tab = f"Scouting_{event_code}"
    elif f"Captura_{event_code}" in sheet_titles:
        scouting_tab = f"Captura_{event_code}"
    elif "Captura_BIOBUZZ" in sheet_titles:
        scouting_tab = "Captura_BIOBUZZ"
    else:
        scouting_tab = sheet_titles[0]

    ws_form = spreadsheet.worksheet(scouting_tab)
    scouting_df = pd.DataFrame(ws_form.get_all_records())

    if scouting_df.empty:
        print(f"[WARN] La pestaña '{scouting_tab}' está vacía.")
        return pd.DataFrame(), pd.DataFrame(columns=["Team ID", "Names"]), pd.DataFrame(columns=["match_code", "RED1", "RED2", "BLUE1", "BLUE2"])

    scouting_df.columns = [str(c).strip() for c in scouting_df.columns]

    # Normalizar nombres de columnas del Google Form / Sheets real hacia el estándar interno
    scouting_df = scouting_df.rename(columns={
        "POSICIÓN INICIAL" : "POS INICIAL",
        "AUTO HIVE POLLEN" : "AUTO HIVE POLEN",
        "AUTO FLOR POLLEN" : "AUTO FLOR POLEN",
        "TELE HIVE POLLEN" : "TELE HIVE POLEN",
        "TELE FLOR POLLEN" : "TELE FLOR POLEN",
    })

    # Filtrar por columna EVENTO si existe en la hoja
    if "EVENTO" in scouting_df.columns:
        scouting_df = scouting_df[
            scouting_df["EVENTO"].astype(str).str.strip().str.upper() == event_code.upper()
        ].reset_index(drop=True)

    # Limpieza de EQUIPO y MATCH
    if "EQUIPO" in scouting_df.columns:
        scouting_df["EQUIPO"] = pd.to_numeric(scouting_df["EQUIPO"], errors="coerce").fillna(0).astype(int)
