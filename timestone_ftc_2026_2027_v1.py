def temporal_weight(series):
    """Ponderación lineal creciente para los últimos 8 matches (más reciente = mayor peso)."""
    pts    = list(series)
    recent = pts[-8:]
    result = []
    for i, val in enumerate(recent):
        result.extend([val] * (i + 1))
    return result

def safe_mode(data_list, default_value="NO"):
    """Calcula la moda estadística con respaldo seguro."""
    if not data_list:
        return default_value
    try:
        return std.mode(data_list)
    except (std.StatisticsError, Exception):
        vals, counts = np.unique(data_list, return_counts=True)
        return vals[np.argmax(counts)] if len(vals) > 0 else default_value

def normalise_match_id(raw):
    """Normaliza cualquier identificador de match (ej. 'Q-3', '03', 3) a entero."""
    s = str(raw).strip()
    m = re.search(r'(\d+)$', s)
    if m:
        return int(m.group(1))
    try:
        return int(s)
    except ValueError:
        return None

