    if "MATCH" in scouting_df.columns:
        scouting_df["MATCH"] = scouting_df["MATCH"].apply(normalise_match_id)

    # ── 2. CARGA DE EQUIPOS DEL EVENTO ─────────────────────────────────────────
    teams_tab = f"Equipos_{event_code}" if f"Equipos_{event_code}" in sheet_titles else ("Equipos" if "Equipos" in sheet_titles else None)

    if teams_tab:
        teams_names_df = pd.DataFrame(spreadsheet.worksheet(teams_tab).get_all_records())
        teams_names_df.columns = [str(c).strip() for c in teams_names_df.columns]
        if "EVENTO" in teams_names_df.columns:
            teams_names_df = teams_names_df[
                teams_names_df["EVENTO"].astype(str).str.strip().str.upper() == event_code.upper()
            ].reset_index(drop=True)
    else:
        unique_teams = sorted(scouting_df["EQUIPO"].unique()) if not scouting_df.empty else []
        teams_names_df = pd.DataFrame({
            "Team ID": unique_teams,
            "Names"  : [f"Equipo {t}" for t in unique_teams]
        })

    # ── 3. CARGA DE MATCHES DEL EVENTO ─────────────────────────────────────────
    matches_tab = f"Matches_{event_code}" if f"Matches_{event_code}" in sheet_titles else ("Matches" if "Matches" in sheet_titles else None)

    if matches_tab:
        matches_df = pd.DataFrame(spreadsheet.worksheet(matches_tab).get_all_records())
        matches_df.columns = [str(c).strip() for c in matches_df.columns]
        if "EVENTO" in matches_df.columns:
            matches_df = matches_df[
                matches_df["EVENTO"].astype(str).str.strip().str.upper() == event_code.upper()
            ].reset_index(drop=True)
        if "match_code" in matches_df.columns:
            matches_df["match_code"] = matches_df["match_code"].apply(normalise_match_id)
    else:
        matches_list = []
